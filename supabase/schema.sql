create or replace function public.compute_bonus_points(champion_prediction text, runner_up_prediction text)
returns integer
language sql
stable
set search_path = public
as $$
  with rules as (
    select
      coalesce((value->>'champion')::integer, 5) as champion_points,
      coalesce((value->>'runner_up')::integer, 3) as runner_up_points
    from public.settings
    where key = 'scoring_rules'
  ), official as (
    select
      value->>'champion' as champion,
      value->>'runner_up' as runner_up
    from public.settings
    where key = 'official_result'
  ), defaults as (
    select
      coalesce((select champion_points from rules), 5) as champion_points,
      coalesce((select runner_up_points from rules), 3) as runner_up_points,
      (select champion from official) as champion,
      (select runner_up from official) as runner_up
  )
  select
    case
      when nullif(trim(coalesce(defaults.champion, '')), '') is not null
       and lower(trim(coalesce(champion_prediction, ''))) = lower(trim(defaults.champion))
      then defaults.champion_points else 0 end
    +
    case
      when nullif(trim(coalesce(defaults.runner_up, '')), '') is not null
       and lower(trim(coalesce(runner_up_prediction, ''))) = lower(trim(defaults.runner_up))
      then defaults.runner_up_points else 0 end
  from defaults;
$$;

