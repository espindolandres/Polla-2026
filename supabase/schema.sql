security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.profiles p
    where p.id = check_user_id
      and p.role = 'admin'
  );
$$;

create or replace function public.is_match_open_for_predictions(check_match_id bigint)
returns boolean
language sql
stable
