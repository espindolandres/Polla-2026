begin;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  full_name text,
  alias text unique not null check (length(trim(alias)) > 0),
  role text not null default 'user' check (role in ('user', 'admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.matches (
  id bigint generated by default as identity primary key,
  match_number integer unique,
  phase text,
  group_name text,
  home_team text,
  away_team text,
  match_date timestamptz,
  stadium text,
  city text,
  home_score integer check (home_score is null or home_score >= 0),
  away_score integer check (away_score is null or away_score >= 0),
  status text not null default 'scheduled' check (status in ('scheduled', 'live', 'finished')),
  created_at timestamptz not null default now()
);

create table if not exists public.predictions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  match_id bigint not null references public.matches(id) on delete cascade,
  predicted_home_score integer check (predicted_home_score is null or predicted_home_score >= 0),
  predicted_away_score integer check (predicted_away_score is null or predicted_away_score >= 0),
  points integer not null default 0,
  exact_score boolean not null default false,
  correct_result boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(user_id, match_id)
);

create table if not exists public.bonus_predictions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  champion text,
  runner_up text,
  top_scorer text,
  surprise_team text,
  points integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(user_id)
);

create table if not exists public.settings (
  key text primary key,
  value jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create index if not exists idx_matches_date on public.matches(match_date);
create index if not exists idx_matches_phase on public.matches(phase);
create index if not exists idx_predictions_user_id on public.predictions(user_id);
create index if not exists idx_predictions_match_id on public.predictions(match_id);
create index if not exists idx_bonus_predictions_user_id on public.bonus_predictions(user_id);

insert into public.settings (key, value) values
  ('scoring_rules', '{"exact_score": 3, "correct_result": 1, "champion": 5, "runner_up": 3}'::jsonb),
  ('bonus_lock_at', '{"lock_at": "2026-06-11T00:00:00.000Z"}'::jsonb),
  ('official_result', '{"champion": null, "runner_up": null}'::jsonb)
on conflict (key) do nothing;

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  raw_alias text;
  raw_full_name text;
begin
  raw_alias := nullif(trim(new.raw_user_meta_data->>'alias'), '');
  raw_full_name := nullif(trim(new.raw_user_meta_data->>'full_name'), '');

  if raw_alias is null then
    raise exception 'El alias es obligatorio';
  end if;

  insert into public.profiles (id, email, full_name, alias, role)
  values (new.id, new.email, raw_full_name, raw_alias, 'user');

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

