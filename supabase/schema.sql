create or replace function public.match_result(home_score integer, away_score integer)
returns text
language sql
immutable
as $$
  select case
    when home_score is null or away_score is null then null
    when home_score > away_score then 'home_win'
    when away_score > home_score then 'away_win'
    else 'draw'
  end;
$$;

create or replace function public.compute_match_points(
  predicted_home integer,
  predicted_away integer,
  actual_home integer,
  actual_away integer,
  match_status text
)
returns table(points integer, exact_score boolean, correct_result boolean)
language sql
stable
set search_path = public
as $$
  with rules as (
    select
      coalesce((value->>'exact_score')::integer, 3) as exact_score_points,
      coalesce((value->>'correct_result')::integer, 1) as correct_result_points
    from public.settings
    where key = 'scoring_rules'
  ), defaults as (
    select
      coalesce((select exact_score_points from rules), 3) as exact_score_points,
      coalesce((select correct_result_points from rules), 1) as correct_result_points
  )
  select
    case
      when match_status <> 'finished' then 0
      when predicted_home is null or predicted_away is null or actual_home is null or actual_away is null then 0
      when predicted_home = actual_home and predicted_away = actual_away then defaults.exact_score_points
      when public.match_result(predicted_home, predicted_away) = public.match_result(actual_home, actual_away) then defaults.correct_result_points
      else 0
    end as points,
    case
      when match_status = 'finished'
       and predicted_home is not null and predicted_away is not null and actual_home is not null and actual_away is not null
       and predicted_home = actual_home and predicted_away = actual_away
      then true else false
    end as exact_score,
    case
      when match_status = 'finished'
       and predicted_home is not null and predicted_away is not null and actual_home is not null and actual_away is not null
       and public.match_result(predicted_home, predicted_away) = public.match_result(actual_home, actual_away)
      then true else false
    end as correct_result
  from defaults;
$$;

create or replace function public.set_prediction_scores()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  match_record public.matches%rowtype;
  computed_points integer;
  computed_exact boolean;
  computed_correct boolean;
begin
  if current_setting('app.skip_prediction_score_trigger', true) = 'on' then
    new.updated_at = now();
    return new;
  end if;

  select * into match_record
  from public.matches
  where id = new.match_id;

  select c.points, c.exact_score, c.correct_result
    into computed_points, computed_exact, computed_correct
  from public.compute_match_points(
    new.predicted_home_score,
    new.predicted_away_score,
    match_record.home_score,
    match_record.away_score,
    match_record.status
  ) c;

  new.points := coalesce(computed_points, 0);
  new.exact_score := coalesce(computed_exact, false);
  new.correct_result := coalesce(computed_correct, false);
  new.updated_at := now();

  return new;
end;
$$;

