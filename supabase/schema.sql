create or replace function public.set_user_role(target_user_id uuid, new_role text)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.is_admin(auth.uid()) then
    raise exception 'Solo un administrador puede cambiar roles';
  end if;

  if new_role not in ('user', 'admin') then
    raise exception 'Rol inválido';
  end if;

  update public.profiles
  set role = new_role
  where id = target_user_id;
end;
$$;

create or replace view public.leaderboard_view as
select
  p.id as user_id,
  p.alias,
  coalesce(sum(pr.points), 0)::integer + coalesce(bp.points, 0)::integer as total_points,
  count(pr.id) filter (where pr.exact_score)::integer as exact_scores,
  count(pr.id) filter (where pr.correct_result)::integer as correct_results,
  coalesce(bp.points, 0)::integer as bonus_points,
  bp.champion,
  bp.runner_up,
  greatest(
    coalesce(max(pr.updated_at), p.created_at),
    coalesce(bp.updated_at, p.created_at)
  ) as last_updated
from public.profiles p
left join public.predictions pr on pr.user_id = p.id
left join public.bonus_predictions bp on bp.user_id = p.id
group by p.id, p.alias, p.created_at, bp.points, bp.champion, bp.runner_up, bp.updated_at;

create or replace view public.predictions_export_view
with (security_invoker = true)
as
select
  pr.id,
  p.alias,
  m.match_number,
  m.phase,
  m.group_name,
  m.home_team,
  m.away_team,
  m.match_date,
  pr.predicted_home_score,
  pr.predicted_away_score,
  m.home_score,
  m.away_score,
  pr.points,
  pr.exact_score,
  pr.correct_result,
  pr.updated_at
from public.predictions pr
join public.profiles p on p.id = pr.user_id
join public.matches m on m.id = pr.match_id;

