create or replace function public.refresh_prediction_scores_for_match()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  perform set_config('app.skip_prediction_score_trigger', 'on', true);

  with recalculated as (
    select p.id, c.points, c.exact_score, c.correct_result
    from public.predictions p
    cross join lateral public.compute_match_points(
      p.predicted_home_score,
      p.predicted_away_score,
      new.home_score,
      new.away_score,
      new.status
    ) c
    where p.match_id = new.id
  )
  update public.predictions p
  set points = r.points,
      exact_score = r.exact_score,
      correct_result = r.correct_result,
      updated_at = now()
  from recalculated r
  where p.id = r.id;

  return new;
end;
$$;

drop trigger if exists refresh_prediction_scores_for_match_trigger on public.matches;
create trigger refresh_prediction_scores_for_match_trigger
  after update of home_score, away_score, status on public.matches
  for each row execute function public.refresh_prediction_scores_for_match();

create or replace function public.recalculate_match_points(p_match_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.is_admin(auth.uid()) then
    raise exception 'Solo un administrador puede recalcular puntos';
  end if;

  perform set_config('app.skip_prediction_score_trigger', 'on', true);

  with recalculated as (
    select p.id, c.points, c.exact_score, c.correct_result
    from public.predictions p
    join public.matches m on m.id = p.match_id
    cross join lateral public.compute_match_points(
      p.predicted_home_score,
      p.predicted_away_score,
      m.home_score,
      m.away_score,
      m.status
    ) c
    where p.match_id = p_match_id
  )
  update public.predictions p
  set points = r.points,
      exact_score = r.exact_score,
      correct_result = r.correct_result,
      updated_at = now()
  from recalculated r
  where p.id = r.id;
end;
$$;

